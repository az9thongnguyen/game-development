// =============================================================================
//  tests/test_inflate.cpp  —  our DEFLATE against streams a real zlib produced
// =============================================================================
//  The only test worth having for a decompressor: bytes that a genuine compressor
//  emitted, decoded back to the bytes that went in. The fixtures below were made by
//  Python's zlib at several levels precisely so that all three block types appear —
//  level 0 forces STORED, short inputs get FIXED Huffman, and a long skewed text
//  gets DYNAMIC tables. A decoder that only ever sees one of the three is a decoder
//  that works until someone else's PNG arrives.
//
//  The failure cases matter as much: a corrupt stream must be REFUSED, not decoded
//  into plausible-looking rubbish, because the caller above this is a PNG reader and
//  the symptom of "decoded anyway" is wrong colours nobody can explain.
// =============================================================================
